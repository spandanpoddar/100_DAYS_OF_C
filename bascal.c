#include<stdio.h>
int main()
{
 int a,b;
 
 printf("enter integer value of a:");
 scanf("%d",&a);
 
 printf("enter integer value of b:");
 scanf("%d",&b);
 
 printf("the sum of: %d + %d is %d\n", a,b,a+b);
 printf("the difference of: %d - %d is %d\n", a,b,a-b);
 printf("the product of: %d * %d is %d\n", a,b,a*b);
 printf("the quotient of: %d / %d is %d\n", a,b,a/b);
}
